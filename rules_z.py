"""Правила классификации для выписок ИП Зайкин (см. NOTES.md). classify(r) -> dict."""


def classify(r):
    o = r["opis"] or ""
    ol = o.lower()

    def res(cp, art, conf, note="", skip=False, desc=None):
        d = {"skip": skip, "cp": cp, "art": art, "conf": conf, "note": note}
        if desc:
            d["desc"] = desc
        return d

    if r["type"] != "Дебет":
        return res("", "", "", "приход (П4)", skip=True)
    bank = ("плата за обслуживание", "оповещение об операциях", "бухгалтерское обслуживание",
            "плата за пакет", "комиссия за внешний банковский перевод", "комиссия за операции по терминалам",
            "плата за активный овердрафт", "плата за использованный лимит овердрафта")
    if any(s in ol for s in bank):
        return res("Т-банк", "банковские расходы", "выс", "П5")
    if "енп" in ol or "налог" in ol or "пени" in ol:
        return res("ФНС", "Налоги и сборы", "выс", "налог/пени")
    if "перевод собственных средств" in ol:
        return res("Зайкин С.", "Зарплата", "выс", "перевод себе = зарплата Зайкин С. (правило Зайкина)",
                   desc="перевод зарплаты")
    return res("?", "?", "—", "НЕТ ПРАВИЛА")
