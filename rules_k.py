"""Правила классификации для выписок ИП Кириллов (см. NOTES.md). classify(r) -> dict."""


def classify(r):
    o = r["opis"] or ""
    ol = o.lower()
    amt = r["debit"]

    def res(cp, art, conf, note="", skip=False):
        return {"skip": skip, "cp": cp, "art": art, "conf": conf, "note": note}

    if r["type"] != "Дебет":
        return res("", "", "", "приход (П4)", skip=True)
    if o.startswith("Перевод собственных средств.") and "на счет" not in ol and "на счёт" not in ol:
        return res("", "", "", "резервный фонд (П12)", skip=True)
    if "возврат средств по терминалам эквайринга" in ol:
        return res("", "", "", "возврат по терминалу (П14)", skip=True)

    bank = ("комиссия за операции по терминалам эквайринга", "плата за пакет", "плата за обслуживание",
            "комиссия за внешний банковский перевод", "плата за использованный лимит овердрафта",
            "плата за активный овердрафт", "оповещение об операциях", "бухгалтерское обслуживание")
    if any(s in ol for s in bank):
        return res("Т-банк", "банковские расходы", "выс", "П5")
    if "плата за пополнение по операции сбп" in ol:
        return res("Т-банк", "банковские расходы", "ср", "комиссия СБП — новое, подтвердить")
    if any(s in ol for s in ("vkusvill", "onetwotrip", "sber life", "wildberries")) or ol.startswith("оплата в ekc "):
        return res("Иван Кириллов", "Иван Кириллов", "выс", "П13")
    if "cdek" in ol:
        return res("неясно", "неясно", "ср", "CDEK картой — пока «неясно» (решение 06.10, пользователь разберётся)")
    if "yandex" in ol and "dostavka" in ol:
        return res("яндексдоставка", "Транспортные расходы", "выс", "Яндекс Доставка")
    if "аренд" in ol:
        return res("Аренда офиса Козупеев", "Аренда", "ср", "проверить получателя")
    if "трофименко" in (r["recv_name"] or "").lower():
        return res("ИП Трофименко В.В.", "Маркетинг и реклама", "выс", "П9")
    if "программист" in ol or "разработчик" in ol:
        return res("?", "Маркетинг и реклама", "ср", "программист — уточнить контрагента")
    if "insales" in ol:
        return res("Insales", "Маркетинг и реклама", "выс", "правило")
    if "avito" in ol and "dostavka" in ol:
        return res("авито закупка", "Закупка товаров", "ср", "П8 Доставка")
    if "avito" in ol:
        if amt % 1000 == 0:
            return res("Авито реклама", "Маркетинг и реклама", "ср", "П8 ровная")
        return res("Авито реклама", "Маркетинг и реклама", "низ", "П8 неровная — проверить")
    if "перевод собственных средств на счет" in ol or "перевод собственных средств на счёт" in ol:
        return res("?", "?", "—", "П6 — перевод себе, уточнить")
    return res("?", "?", "—", "НЕТ ПРАВИЛА — уточнить")
