"""Правила классификации для выписок ИП Давыдов (см. NOTES.md). classify(r) -> dict."""


def classify(r):
    o = r["opis"] or ""
    ol = o.lower()
    amt = r["debit"]
    recv = (r.get("recv_name") or "")

    def res(cp, art, conf, note="", skip=False):
        return {"skip": skip, "cp": cp, "art": art, "conf": conf, "note": note}

    if r["type"] != "Дебет":
        return res("", "", "", "приход (П4)", skip=True)
    if "погашение разрешенного овердрафта" in ol or ("предоставление" in ol and "овердрафт" in ol):
        return res("", "", "", "овердрафт-механика (П5)", skip=True)
    if "возврат средств по терминалам эквайринга" in ol:
        return res("", "", "", "возврат по терминалу (П14)", skip=True)

    bank = ("комиссия за внешний банковский перевод", "плата за активный овердрафт",
            "плата за использованный лимит овердрафта", "плата за обслуживание", "плата за пакет",
            "доплата до минимального платежа", "комиссия за операции по терминалам эквайринга",
            "оповещение об операциях", "бухгалтерское обслуживание")
    if any(s in ol for s in bank):
        return res("Т-банк", "банковские расходы", "выс", "П5")
    if "плата за пополнение по операции сбп" in ol:
        return res("Т-банк", "банковские расходы", "ср", "комиссия СБП")
    if "енп" in ol or "аусн" in ol:
        return res("ФНС", "Налоги и сборы", "выс", "налог")
    if "dns" in ol:
        return res("DNS", "Закупка запчастей", "выс", "DNS")
    if "ozon" in ol or "озон" in ol:
        return res("озон", "Закупка запчастей", "ср", "OZON — уточнять каждый раз (обычно запчасти)")
    if "yandex" in ol and "market" in ol:
        return res("?", "?", "—", "Яндекс Маркет — что купили?")
    if "yandex" in ol and ("dostavka" in ol or "*go" in ol):
        return res("яндексдоставка", "Транспортные расходы", "выс", "Яндекс")
    if "avito" in ol and "dostavka" in ol:
        return res("авито закупка", "Закупка товаров", "ср", "П8 Доставка")
    if "avito" in ol:
        if amt % 1000 == 0:
            return res("Авито реклама", "Маркетинг и реклама", "ср", "П8 ровная")
        return res("Авито реклама", "Маркетинг и реклама", "низ", "П8 неровная — проверить")
    if "noya-ai" in ol:
        return res("noya ai", "Маркетинг и реклама", "выс", "ИИ-сервис")
    if "syntx" in ol:
        return res("ИИ сервисы", "Маркетинг и реклама", "выс", "ИИ-сервис")
    if "aliexpress" in ol:
        return res("Aliexpress.ru", "Диски и опера", "ср", "AliExpress")
    if "трофименко" in recv.lower():
        return res("ИП Трофименко В.В.", "Маркетинг и реклама", "выс", "П9")
    if "зедакс" in recv.lower() or "зедакс" in ol:
        return res("Зедакс (Сдэк)", "Транспортные расходы", "выс", "ЗЕДАКС = СДЭК")
    if "3delectronics" in ol:
        return res("3д электроникс", "Закупка товаров", "выс", "правило")
    if "pyaterochka" in ol or "fixprice" in ol or "avtozavodskaya" in ol:
        return res("Хозрасходы", "хозяйственные расходы", "ср", "мелкие бытовые покупки")
    if "договору стоянки" in ol:
        return res("Лось И.", "Зарплата", "низ", "в августе (14.08) такой платёж был зарплатой Лось И. — подтвердить")
    if "перевод собственных средств" in ol:
        return res("?", "?", "—", "перевод себе — уточнить")
    return res("?", "?", "—", f"НЕТ ПРАВИЛА — получатель: {recv[:40]}")
